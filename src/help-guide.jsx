function Para(p) {
  var t = String(p.t || "");
  if (t.indexOf("· ") === 0) return (<div style={{ display: "flex", gap: 7, margin: "3px 0", lineHeight: 1.7 }}><span style={{ color: "var(--acc)", flexShrink: 0 }}>{"•"}</span><span style={{ minWidth: 0 }}>{t.slice(2)}</span></div>);
  return (<p style={{ margin: "5px 0", lineHeight: 1.75 }}>{t}</p>);
}

